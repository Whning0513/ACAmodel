def _extract_test_inputs(msg) -> list:
    """Extract test_inputs from an AIMessage tool call."""
    if not hasattr(msg, "tool_calls") or not msg.tool_calls:
        return []
    tc = msg.tool_calls[0]
    args = tc.get("args", {})
    inputs = args.get("test_inputs", [])
    if isinstance(inputs, str):
        return [inputs]
    return [str(x) for x in inputs] if isinstance(inputs, list) else [str(inputs)]


def _parse_batch_coverage(content: str):
    """Parse batch-level newly_covered and remaining from ToolMessage content.

    Returns (newly_covered: list, remaining: list).
    """
    newly_covered = []
    remaining = []
    for line in content.split("\n"):
        line = line.strip()
        if line.startswith("Lines covered by this batch:") or line.startswith("New target lines covered:"):
            val = line.split(":", 1)[1].strip()
            newly_covered = _parse_compact_lines(val)
        elif line.startswith("Target lines STILL UNCOVERED:") or line.startswith("Remaining target lines:"):
            val = line.split(":", 1)[1].strip()
            remaining = _parse_compact_lines(val)
        elif line.startswith("All target lines covered."):
            remaining = []
    return newly_covered, remaining


def _parse_compact_lines(s: str) -> list:
    """Parse compact line range string back to list of ints.

    Handles both formats:
      '1-3,5-6' → [1,2,3,5,6]    (compact format from nodes.py)
      '[22, 23]' → [22, 23]       (Python repr from batch summary)
      '[]' → []
      '22' → [22]
    """
    s = s.strip()
    if not s or s == "[]":
        return []
    # Python list repr: "[22, 23]" or "[22]"
    if s.startswith("[") and s.endswith("]"):
        inner = s[1:-1].strip()
        if not inner:
            return []
        result = []
        for part in inner.split(","):
            part = part.strip()
            if part:
                result.append(int(part))
        return result
    # Compact format: "1-3,5-6" or "22"
    result = []
    for part in s.split(","):
        part = part.strip()
        if "-" in part:
            a, b = part.split("-", 1)
            result.extend(range(int(a), int(b) + 1))
        elif part:
            result.append(int(part))
    return result


def _parse_per_case_results(content: str) -> list:
    """Parse per-input results from ToolMessage content into CaseResult list.

    The ToolMessage is a human-readable text block generated by _handle_run_and_trace.
    We parse it back to structured data for trajectory reconstruction.
    Format from _handle_run_and_trace:
        1. [WA] 7\\n14\\n21 | stu='Yes' expected='No' | cov=1-3,5-6 new=22
        2. [SURVIVED] 1 1 1 | cov=[]
    """
    results = []
    # Both SURVIVED and COVERAGE mean student output matched reference (AC).
    # The label only differs in whether new target lines were covered.
    label_to_status = {
        "WA": "WA",
        "RE": "RE",
        "OOM": "OOM",
        "MLE": "MLE",
        "SURVIVED": "AC",
        "COVERAGE": "AC",
        "TLE": "TLE",
        "INVALID": "INVALID",
        "AC": "AC",
        "COUNTERCASE_WA": "WA",
        "COUNTERCASE_RE": "RE",
        "INCOMPARABLE": "INVALID",
        "TIMEOUT": "TIMEOUT",
    }
    for line in content.split("\n"):
        line = line.strip()
        if not line or not line[0].isdigit():
            continue
        try:
            # Extract label
            label_start = line.index("[") + 1
            label_end = line.index("]", label_start)
            label = line[label_start:label_end]
            status = label_to_status.get(label, label)

            # New format may omit the input and only provide status/new_lines/note.
            # Legacy format includes input between "] " and first " | ".
            after_label = line[label_end + 2:]  # skip "] "
            if "new_lines=" in after_label and "note=" in after_label and " | " not in after_label:
                test_input = ""
                cov_list = []
                is_ac = status == "AC"
                results.append({
                    "test_input": test_input,
                    "status": status,
                    "covered_lines": cov_list,
                    "is_ac": is_ac,
                })
                continue
            pipe_idx = after_label.find(" | ")
            inp_compact = after_label[:pipe_idx] if pipe_idx >= 0 else after_label
            test_input = inp_compact.replace("\\n", "\n")

            # Extract cov=... after structural separator (robust against cov= in error text)
            cov_idx = line.find(" | cov=")
            cov_list = []
            if cov_idx >= 0:
                cov_val = line[cov_idx + 7:].split()[0] if line[cov_idx + 7:].split() else line[cov_idx + 7:]
                cov_list = _parse_compact_lines(cov_val)

            is_ac = status == "AC"
            results.append({
                "test_input": test_input,
                "status": status,
                "covered_lines": cov_list,
                "is_ac": is_ac,
            })
        except (ValueError, IndexError):
            continue
    return results


def _reconstruct_trajectory(state: Dict[str, Any]) -> list:
    """Build structured IterationRecord list from trajectory_data.

    trajectory_data is populated by _handle_run_and_trace alongside each
    ToolMessage — it contains full stdout/stderr/expected_output without
    the truncation imposed by the text-based ToolMessage format.
    """
    traj_data = state.get("trajectory_data", [])
    if traj_data:
        return _build_trajectory_from_data(traj_data)

    # Fallback: reconstruct from message history for runs that predate
    # trajectory_data (backward compatibility with old result files).
    return _reconstruct_trajectory_from_messages(state)


def _build_trajectory_from_data(traj_data: list) -> list:
    """Build IterationRecord list from structured trajectory_data."""
    trajectory = []
    for entry in traj_data:
        per_case_results = [
            CaseResult(
                test_input=cr["test_input"],
                status=cr["status"],
                covered_lines=cr.get("covered_lines", []),
                stdout=cr.get("stdout", ""),
                stderr=cr.get("stderr", ""),
                expected_output=cr.get("expected_output", ""),
                is_ac=cr.get("is_ac", False),
            )
            for cr in entry.get("per_case_results", [])
        ]
        trajectory.append(IterationRecord(
            iteration=entry["iteration"],
            uncovered_before=entry.get("uncovered_before", []),
            test_inputs=entry.get("test_inputs", []),
            per_case_results=per_case_results,
            newly_covered=entry.get("newly_covered", []),
            breakthroughs=entry.get("breakthroughs", []),
            thought_process=entry.get("thought_process", ""),
            stagnation=entry.get("stagnation", False),
        ))
    return trajectory


def _reconstruct_trajectory_from_messages(state: Dict[str, Any]) -> list:
    """Legacy path: reconstruct from message history for pre-trajectory_data runs."""
    messages = state.get("messages", [])
    trajectory = []
    current_inputs = []
    current_thought = ""

    for msg in messages:
        role = type(msg).__name__

        if role == "AIMessage":
            current_inputs = _extract_test_inputs(msg)
            current_thought = msg.content or ""

        elif role == "ToolMessage" and current_inputs:
            content = msg.content or ""
            breakthroughs = []

            # Parse per-case results from ToolMessage content
            case_results = _parse_per_case_results(content)

            # Extract breakthroughs from case results (always correctly unescaped)
            breakthroughs = [
                cr["test_input"] for cr in case_results
                if cr["status"] in ("WA", "RE", "TLE", "MLE", "OOM")
            ]

            # Parse batch-level newly_covered and remaining from summary
            batch_newly, batch_remaining = _parse_batch_coverage(content)
            uncovered_before = sorted(set(batch_newly) | set(batch_remaining))

            # Check stagnation: no coverage gains or bugs in any per-input line
            stagnation = (
                len(batch_newly) == 0 and len(breakthroughs) == 0
            )

            record = IterationRecord(
                iteration=len(trajectory) + 1,
                uncovered_before=uncovered_before,
                test_inputs=current_inputs,
                per_case_results=[
                    CaseResult(
                        test_input=cr["test_input"],
                        status=cr["status"],
                        covered_lines=cr.get("covered_lines", []),
                        is_ac=cr.get("is_ac", False),
                    )
                    for cr in case_results
                ],
                newly_covered=batch_newly,
                breakthroughs=breakthroughs,
                thought_process=current_thought,
                stagnation=stagnation,
            )
            trajectory.append(record)
            current_inputs = []

    return trajectory


def _write_debug_trace(result: dict, submission_id: str, trace_dir: str):
    """Write full conversation trace to {trace_dir}/{submission_id}_trace.json."""
    os.makedirs(trace_dir, exist_ok=True)
    messages = result.get("messages", [])

    trace = []
    for i, msg in enumerate(messages):
        role = type(msg).__name__
        entry = {"index": i, "role": role}

        if hasattr(msg, "content"):
            entry["content"] = msg.content or ""

        if hasattr(msg, "tool_calls") and msg.tool_calls:
            entry["tool_calls"] = [
                {"id": tc.get("id", ""), "name": tc["name"],
                 "args": tc.get("args", {})}
                for tc in msg.tool_calls
            ]

        if hasattr(msg, "tool_call_id"):
            entry["tool_call_id"] = msg.tool_call_id

        if hasattr(msg, "additional_kwargs") and msg.additional_kwargs:
            if "reasoning_content" in msg.additional_kwargs:
                entry["reasoning"] = msg.additional_kwargs["reasoning_content"]

        trace.append(entry)

    filepath = os.path.join(trace_dir, f"{submission_id}_trace.json")
    payload = {
        "terminated_reason": result.get("terminated_reason", ""),
        "stop_reason": result.get("stop_reason", ""),
        "error": result.get("error", ""),
        "countercases": result.get("countercases", []),
        "first_countercase_round": result.get("first_countercase_round"),
        "first_countercase_input": result.get("first_countercase_input"),
        "conversation": trace,
    }
    with open(filepath, "w") as f:
        json.dump(payload, f, indent=2, ensure_ascii=False)

    # Also write a human-readable markdown version
    md_path = os.path.join(trace_dir, f"{submission_id}_trace.md")
    with open(md_path, "w") as f:
        f.write(f"# Trace: {submission_id}\n\n")
        f.write(f"Terminated: {result.get('terminated_reason', '?')}\n")
        f.write(f"Countercases: {len(result.get('countercases', []))}\n")
        f.write(f"Final uncovered: {result.get('uncovered_lines', [])}\n\n")
        f.write("---\n\n")
        for entry in trace:
            role = entry["role"]
            content = entry.get("content", "")
            f.write(f"## {entry['index']}. {role}\n\n")
            if entry.get("tool_calls"):
                for tc in entry["tool_calls"]:
                    f.write(f"- **Tool call**: `{tc['name']}`\n")
                    f.write(f"```json\n{json.dumps(tc['args'], indent=2, ensure_ascii=False)}\n```\n\n")
            if entry.get("reasoning"):
                f.write(f"<details><summary>Reasoning</summary>\n\n{entry['reasoning']}\n\n</details>\n\n")
            if content:
                # Truncate very long tool results
                if role == "ToolMessage" and len(content) > 5000:
                    content = content[:5000] + "\n\n... (truncated)"
                f.write(f"{content}\n\n")


def _extract_llm_error_message(payload: Any) -> Optional[str]:
    if not payload:
        return None
    if isinstance(payload, dict):
        if payload.get("message"):
            return str(payload["message"])
        return str(payload)
    return str(payload)


def process_one_submission(
    rec: InputRecord,
    config: R1Config,
    test_cases: Dict[str, list],
    description_html: str = "",
    verbose: bool = False,
    trace_dir: Optional[str] = None,
    trajectory_dir: Optional[str] = None,
) -> SubmissionResult:
    """Run the R-family agent on one submission.

    Args:
        rec: SubmissionRecord from ACA.tool.problem_loader.
        config: R1Config or R1_1Config.
        test_cases: pid → [{input, _norm_out}, ...] from step4_references.
        description_html: Problem description (loaded externally).
        verbose: Print debug output.

    Returns:
        SubmissionResult with full trajectory.
    """
    t_start = time.time()
    writer = TrajectoryWriter(
        trajectory_dir,
        config.strategy,
        rec.submission_id,
        keep_full_text=bool(trace_dir),
    )
    writer.append_event({
        "event_type": "submission_start",
        "strategy": config.strategy,
        "model": config.model,
        "submission_id": rec.submission_id,
        "pid": rec.pid,
        "source": rec.source,
        "source_kind": getattr(rec, "source_kind", None),
        "initial_target_lines": rec.uncovered_effective_lines,
        "code_size_lines": getattr(rec, "code_size_lines", None),
        "max_iterations": getattr(config, "max_iterations", None),
        "patience": getattr(config, "patience", None),
        "run_timeout": getattr(config, "run_timeout", None),
        "run_label": str(writer.path.parent.parent.parent) if writer.path else None,
        "trajectory_path": str(writer.path) if writer.path else None,
    })

    def _finish(result: SubmissionResult) -> SubmissionResult:
        end_payload = compute_submission_end_fields(
            result.trajectory,
            rec.uncovered_effective_lines,
            result.final_uncovered_lines,
        )
        writer.append_event({
            "event_type": "submission_end",
            "strategy": config.strategy,
            "submission_id": rec.submission_id,
            "terminated_reason": result.terminated_reason,
            "final_uncovered_lines": result.final_uncovered_lines,
            "total_iterations": result.iterations,
            "duplicate_exact_inputs": writer.duplicate_exact_inputs,
            "error": result.error,
            **end_payload,
        })
        writer.close()
        return result

    client = LLMClient(config.to_llm_config())
    client.set_logger(lambda tag, data: None)  # noop logger for now
    prompt_view = resolve_prompt_view(rec)

    agent_node_fn = make_agent_node(config, client, writer)
    tool_executor_node_fn = make_tool_executor_node(config, writer)
    graph = build_graph(config, agent_node_fn, tool_executor_node_fn)

    # Build initial state from the step6 record
    state_dict = make_initial_state(
        submission_id=rec.submission_id,
        pid=rec.pid,
        source=rec.source,
        code_text=rec.code,
        prompt_code_text=prompt_view.code_text,
        ref_code=rec.ref_code,
        ac_indices=rec.ac_indices,
        gt_indices=rec.gt_indices,
        uncovered_effective_lines=rec.uncovered_effective_lines,
        candidate_lines=rec.candidate_lines,
        uncovered_line_tags={str(k): v for k, v in rec.uncovered_line_tags.items()},
        ac_count=rec.ac_count,
        gt_count=rec.gt_count,
        total_cases=rec.total_cases,
        ac_ratio=rec.ac_ratio,
        max_depth=rec.max_depth,
        code_size_lines=rec.code_size_lines,
        code_size_chars=rec.code_size_chars,
        description_html=description_html,
        sample_input_anchor=getattr(rec, "sample_input_anchor", ""),
        prompt_uncovered_lines=prompt_view.target_lines,
        prompt_view_version=prompt_view.prompt_view_version,
        strategy=config.strategy,
        parent_submission_id=rec.parent_submission_id,
        buggy_lines=rec.buggy_lines,
        dropped_ac_indices=rec.dropped_ac_indices,
    )

    # Run graph in a thread with timeout
    import threading
    result_holder = []
    error_holder = []

    def _run():
        try:
            result_holder.append(graph.invoke(state_dict))
        except Exception as e:
            error_holder.append(e)

    thread = threading.Thread(target=_run, daemon=True)
    thread.start()
    # Fast models need less time per graph invocation than slow reasoning models
    _model_lower = config.model.lower()
    graph_timeout = 800 if any(kw in _model_lower for kw in ("flash", "haiku", "mini")) else 2000
    thread.join(timeout=graph_timeout)

    if error_holder:
        elapsed = time.time() - t_start
        return _finish(SubmissionResult(
            submission_id=rec.submission_id,
            pid=rec.pid,
            source=rec.source,
            strategy=config.strategy,
            trajectory=[],
            final_uncovered_lines=rec.uncovered_effective_lines,
            terminated_reason="graph_error",
            countercases=[],
            total_newly_covered=0,
            total_stagnation=0,
            iterations=0,
            elapsed_sec=round(elapsed, 1),
            stop_reason="graph_error",
            error=str(error_holder[0]),
        ))

    if thread.is_alive():
        elapsed = time.time() - t_start
        return _finish(SubmissionResult(
            submission_id=rec.submission_id,
            pid=rec.pid,
            source=rec.source,
            strategy=config.strategy,
            trajectory=[],
            final_uncovered_lines=rec.uncovered_effective_lines,
            terminated_reason="graph_timeout",
            countercases=[],
            total_newly_covered=0,
            total_stagnation=0,
            iterations=0,
            elapsed_sec=round(elapsed, 1),
            stop_reason="graph_timeout",
            error=f"graph.invoke timed out after {graph_timeout}s",
        ))

    result = result_holder[0]
    elapsed = time.time() - t_start

    # Write debug trace if requested
    if trace_dir:
        _write_debug_trace(result, rec.submission_id, trace_dir)

    trajectory = _reconstruct_trajectory(result)
    final_uncovered = result.get("uncovered_lines", [])
    countercases = result.get("countercases", [])
    total_newly_covered = len(rec.uncovered_effective_lines) - len(final_uncovered)
    total_stagnation = sum(1 for t in trajectory if t.stagnation)
    llm_error_message = _extract_llm_error_message(result.get("error"))

    if verbose:
        reason = result.get("terminated_reason", "?")
        iters = len(trajectory)
        print(
            f"  [{rec.submission_id}] {reason} | {total_newly_covered} newly covered | "
            f"{len(countercases)} CCs | {iters} iters | {elapsed:.1f}s",
            flush=True,
        )

    return _finish(SubmissionResult(
        submission_id=rec.submission_id,
        pid=rec.pid,
        source=rec.source,
        strategy=config.strategy,
        trajectory=trajectory,
        final_uncovered_lines=final_uncovered,
        terminated_reason=result.get("terminated_reason", "unknown"),
        countercases=countercases,
        total_newly_covered=total_newly_covered,
        total_stagnation=total_stagnation,
        iterations=len(trajectory),
        elapsed_sec=round(elapsed, 1),
        stop_reason=result.get("stop_reason") or result.get("terminated_reason", "unknown"),
        first_countercase_round=result.get("first_countercase_round"),
        first_countercase_input=result.get("first_countercase_input"),
        error=llm_error_message,
    ))
